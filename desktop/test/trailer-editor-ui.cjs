const {app}=require('electron');
const fs=require('node:fs');
const path=require('node:path');
const os=require('node:os');
const net=require('node:net');
const assert=require('node:assert/strict');
const {execFileSync}=require('node:child_process');
const {setTimeout:delay}=require('node:timers/promises');
const {configuration}=require('../src/config.cjs');
const {ApiProcess}=require('../src/api-process.cjs');
const {createWindow}=require('../src/window.cjs');
const root=fs.mkdtempSync(path.join(os.tmpdir(),'onfilm-trailer-ui-'));
fs.mkdirSync(path.join(root,'electron'));app.setPath('userData',path.join(root,'electron'));
app.on('window-all-closed',()=>{});
let win,backend;
const js=script=>win.webContents.executeJavaScript(script);
async function wait(script){console.log('Checking: '+script);const until=Date.now()+90000;while(Date.now()<until){if(await Promise.race([js(script).catch(()=>false),delay(5000,false)]))return;await delay(100);}throw new Error('Trailer UI timeout: '+script);}
async function run(){
  await app.whenReady();
  const server=net.createServer();await new Promise(r=>server.listen(0,'127.0.0.1',r));const port=server.address().port;await new Promise(r=>server.close(r));
  const jar=path.join(root,'api.jar');fs.copyFileSync(process.env.ONFILM_TEST_JAR||path.resolve(__dirname,'../../backend/build-verification/libs/onfilm-local.jar'),jar);
  const config=configuration(path.join(root,'data'),{port,jar,java:process.env.ONFILM_JAVA_PATH});config.env.LOGGING_LEVEL_ROOT='WARN';backend=new ApiProcess(config);
  const original=path.join(root,'original.mp4');
  execFileSync(process.env.ONFILM_FFMPEG||'ffmpeg',['-nostdin','-v','error','-f','lavfi','-i','testsrc=size=160x120:rate=10','-t','4','-c:v','libx264','-threads','1','-pix_fmt','yuv420p',original]);
  win=createWindow({origin:config.origin,backend,token:config.env.ONFILM_TOKEN,dataDir:config.env.ONFILM_DATA_DIR,partition:'trailer-ui-test'});
  await wait("document.getElementById('status')?.textContent==='저장된 프로필을 불러왔습니다.' || document.getElementById('viewStatus')?.textContent==='저장된 프로필입니다.'");
  assert.equal(await js("fetch('/api/profile',{method:'PUT',headers:{'Content-Type':'application/json'},body:JSON.stringify({name:'편집 테스트',oneLineIntro:'',version:0})}).then(r=>r.status)"),200);
  await win.loadURL(config.origin+'/edit-filmography.html');
  await wait("document.getElementById('addFilmBtn')?.disabled===false");
  await js("document.getElementById('addFilmBtn').click();{const input=document.querySelector('[data-field=title]');input.value='트레일러 테스트';input.dispatchEvent(new Event('input'));}");
  assert.equal(await js("document.querySelector('.trailer-from-source').disabled"),true);
  const bytes=[...fs.readFileSync(original)];
  await js(`{const input=document.querySelector('.video-dropzone input[type=file]');const transfer=new DataTransfer();transfer.items.add(new File([new Uint8Array(${JSON.stringify(bytes)})],'original.mp4',{type:'video/mp4'}));input.files=transfer.files;input.dispatchEvent(new Event('change',{bubbles:true}));}`);
  await wait("document.querySelector('.trailer-from-source')?.disabled===false");
  await js("document.querySelector('.trailer-from-source').click()");
  await wait("document.querySelector('.trailer-create')?.disabled===false");
  await wait("document.querySelector('.trailer-editor-video')?.readyState>=1");
  const handle=await js("(()=>{const r=document.querySelector('.trailer-editor-head').getBoundingClientRect();return {x:Math.round(r.left+80),y:Math.round(r.top+18),left:document.querySelector('.trailer-editor').getBoundingClientRect().left};})()");
  win.webContents.sendInputEvent({type:'mouseDown',button:'left',x:handle.x,y:handle.y,clickCount:1});
  win.webContents.sendInputEvent({type:'mouseMove',x:handle.x+30,y:handle.y+12});
  win.webContents.sendInputEvent({type:'mouseUp',button:'left',x:handle.x+30,y:handle.y+12,clickCount:1});
  await delay(200);
  assert(await js(`Math.abs(document.querySelector('.trailer-editor').getBoundingClientRect().left-${handle.left})>5`),'header drag moves dialog');
  assert.equal(await js("typeof require"),'undefined');
  await js("{const input=document.querySelector('.trailer-start-time');input.value='1';input.dispatchEvent(new Event('change'));const end=document.querySelector('.trailer-end-time');end.value='3';end.dispatchEvent(new Event('change'));}");
  assert.equal(await js("document.querySelector('.trailer-selected-length').textContent"),'2.0초');
  assert.equal(await js("document.querySelector('.trailer-preview-fallback, .trailer-start-now, .trailer-end-now')===null"),true);
  await js("document.querySelector('.trailer-loop').click()");
  await wait("document.querySelector('.trailer-loop').getAttribute('aria-pressed')==='true'");
  await delay(2400);
  assert.equal(await js("document.querySelector('.trailer-loop').getAttribute('aria-pressed')"),'true');
  await js("document.querySelector('.trailer-loop').click()");
  assert.equal(await js("document.querySelector('.trailer-loop').getAttribute('aria-pressed')"),'false');
  assert.equal(await js("document.querySelector('.trailer-fullscreen')===null && !document.querySelector('video').hasAttribute('controlslist')"),true,'native bottom-right fullscreen is enabled');
  await js("document.querySelector('video').pause();document.querySelector('.trailer-editor').dispatchEvent(new KeyboardEvent('keydown',{code:'Space',bubbles:true,cancelable:true}))");
  await wait("document.querySelector('video').paused===false");
  await js("document.querySelector('.trailer-editor').dispatchEvent(new KeyboardEvent('keydown',{code:'Space',bubbles:true,cancelable:true}))");
  assert.equal(await js("document.querySelector('video').paused"),true);
  await js("document.querySelector('.trailer-start-range').dispatchEvent(new KeyboardEvent('keydown',{code:'Space',bubbles:true,cancelable:true}))");
  await wait("document.querySelector('video').paused===false");
  await js("document.querySelector('video').pause()");
  await js("document.querySelector('.trailer-editor').dispatchEvent(new KeyboardEvent('keydown',{code:'ArrowRight',bubbles:true,cancelable:true}))");
  await wait("document.querySelector('video').currentTime>=3.9");
  await js("document.querySelector('.trailer-editor').dispatchEvent(new KeyboardEvent('keydown',{code:'ArrowLeft',bubbles:true,cancelable:true}))");
  await wait("document.querySelector('video').currentTime===0");
  assert.equal(await js("(()=>{const event=new KeyboardEvent('keydown',{code:'ArrowRight',bubbles:true,cancelable:true});document.querySelector('.trailer-start-time').dispatchEvent(event);return event.defaultPrevented;})()"),false,'time input keeps normal editing keys');
  await win.webContents.executeJavaScript("document.querySelector('video').requestFullscreen()",true);
  await wait("document.fullscreenElement?.tagName==='VIDEO'");
  await js("document.exitFullscreen()");
  await js("document.querySelector('.trailer-create').click()");
  await wait("document.querySelector('.trailer-accept')?.hidden===false");
  await wait("document.querySelector('video')?.readyState>=1");
  const duration=await js("document.querySelector('video').duration");assert(Math.abs(duration-2)<.2);
  assert.equal(await js("fetch('/api/filmography').then(r=>r.json()).then(d=>d.items.length)"),0);
  await js("document.querySelector('.trailer-accept').click()");
  await wait("!document.querySelector('.trailer-editor') && document.getElementById('saveFilms').disabled===false");
  assert.equal(await js("(()=>{const row=document.querySelector('.trailer-dropzone .media-actions');return getComputedStyle(row).flexWrap==='wrap' && row.scrollWidth<=row.clientWidth+1;})()"),true,'trailer buttons wrap without horizontal overflow');
  await js("document.getElementById('filmographyForm').requestSubmit()");
  await wait("location.pathname==='/profile.html'");
  const saved=await js("fetch('/api/filmography').then(r=>r.json())");assert.equal(saved.trailers.length,1);assert.equal(saved.videos.length,1);
  const originalTrailer=saved.trailers[0].id;
  await win.loadURL(config.origin+'/edit-filmography.html');await wait("document.querySelector('.trailer-from-source')?.disabled===false");
  await js("document.querySelector('.trailer-from-source').click()");await wait("document.querySelector('.trailer-create')?.disabled===false");
  await js("document.querySelector('.trailer-cancel').click()");await wait("!document.querySelector('.trailer-editor')");
  assert.equal(await js("fetch('/api/filmography').then(r=>r.json()).then(d=>d.trailers[0].id)"),originalTrailer);
  console.log('Trailer GUI passed: source upload, time range, repeat toggle, fullscreen, real extraction/HLS, accept/save, cancel preserves saved trailer.');
}
run().then(async()=>{win?.destroy();await backend?.stop();app.exit(0);}).catch(async error=>{console.error(error);win?.destroy();await backend?.stop();app.exit(1);});
