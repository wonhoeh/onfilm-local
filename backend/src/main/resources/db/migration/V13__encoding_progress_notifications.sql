ALTER TABLE encode_job ADD progress INTEGER NOT NULL DEFAULT 0 CHECK (progress BETWEEN 0 AND 100);
UPDATE encode_job SET progress=100 WHERE status='DONE';
CREATE TABLE app_notification (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_id VARCHAR(36) NOT NULL UNIQUE,
    message VARCHAR(500) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    read_at TIMESTAMP
);
CREATE INDEX idx_notification_latest ON app_notification(created_at, id);
